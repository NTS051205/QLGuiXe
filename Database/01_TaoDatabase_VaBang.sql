CREATE TABLE dbo.NHANVIEN
(
    MaNV            VARCHAR(20)    NOT NULL,
    HoTen           NVARCHAR(100)  NOT NULL,
    SoDienThoai     VARCHAR(15)    NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_NHANVIEN_TrangThai DEFAULT ('HOAT_DONG'),
    NgayTaoUtc      DATETIME2(0)   NOT NULL CONSTRAINT DF_NHANVIEN_NgayTaoUtc DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_NHANVIEN PRIMARY KEY (MaNV),
    CONSTRAINT UQ_NHANVIEN_SoDienThoai UNIQUE (SoDienThoai),
    CONSTRAINT CK_NHANVIEN_SoDienThoai CHECK (SoDienThoai NOT LIKE '%[^0-9]%' AND LEN(SoDienThoai) BETWEEN 9 AND 11),
    CONSTRAINT CK_NHANVIEN_TrangThai CHECK (TrangThai IN ('HOAT_DONG', 'TAM_NGHI', 'VO_HIEU'))
);

CREATE TABLE dbo.TAIKHOAN
(
    MaTK            VARCHAR(20)    NOT NULL,
    TenDangNhap     VARCHAR(50)    NOT NULL,
    MatKhauHash     VARCHAR(255)   NOT NULL,
    MaNV            VARCHAR(20)    NOT NULL,
    VaiTro          VARCHAR(20)    NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_TAIKHOAN_TrangThai DEFAULT ('HOAT_DONG'),
    NgayTaoUtc      DATETIME2(0)   NOT NULL CONSTRAINT DF_TAIKHOAN_NgayTaoUtc DEFAULT (SYSUTCDATETIME()),
    LanDangNhapCuoiUtc DATETIME2(0) NULL,
    CONSTRAINT PK_TAIKHOAN PRIMARY KEY (MaTK),
    CONSTRAINT UQ_TAIKHOAN_TenDangNhap UNIQUE (TenDangNhap),
    CONSTRAINT FK_TAIKHOAN_NHANVIEN FOREIGN KEY (MaNV) REFERENCES dbo.NHANVIEN(MaNV),
    CONSTRAINT CK_TAIKHOAN_VaiTro CHECK (VaiTro IN ('ADMIN', 'NHANVIEN')),
    CONSTRAINT CK_TAIKHOAN_TrangThai CHECK (TrangThai IN ('HOAT_DONG', 'KHOA'))
);

CREATE TABLE dbo.CALAM
(
    MaCa            VARCHAR(20)    NOT NULL,
    TenCa           NVARCHAR(50)   NOT NULL,
    GioBatDau       TIME(0)        NOT NULL,
    GioKetThuc      TIME(0)        NOT NULL,
    CONSTRAINT PK_CALAM PRIMARY KEY (MaCa),
    CONSTRAINT UQ_CALAM_TenCa UNIQUE (TenCa),
    CONSTRAINT CK_CALAM_ThoiGian CHECK (GioBatDau <> GioKetThuc)
);

CREATE TABLE dbo.PHANCONGCA
(
    MaPhanCong      VARCHAR(20)    NOT NULL,
    MaNV            VARCHAR(20)    NOT NULL,
    MaCa            VARCHAR(20)    NOT NULL,
    NgayLam         DATE           NOT NULL,
    GhiChu          NVARCHAR(255)  NULL,
    CONSTRAINT PK_PHANCONGCA PRIMARY KEY (MaPhanCong),
    CONSTRAINT UQ_PHANCONGCA_NhanVienCaNgay UNIQUE (MaNV, MaCa, NgayLam),
    CONSTRAINT FK_PHANCONGCA_NHANVIEN FOREIGN KEY (MaNV) REFERENCES dbo.NHANVIEN(MaNV),
    CONSTRAINT FK_PHANCONGCA_CALAM FOREIGN KEY (MaCa) REFERENCES dbo.CALAM(MaCa)
);

CREATE TABLE dbo.KHACHHANG
(
    MaKH            VARCHAR(20)    NOT NULL,
    HoTen           NVARCHAR(100)  NOT NULL,
    SoDienThoai     VARCHAR(15)    NOT NULL,
    NgayTaoUtc      DATETIME2(0)   NOT NULL CONSTRAINT DF_KHACHHANG_NgayTaoUtc DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_KHACHHANG PRIMARY KEY (MaKH),
    CONSTRAINT UQ_KHACHHANG_SoDienThoai UNIQUE (SoDienThoai),
    CONSTRAINT CK_KHACHHANG_SoDienThoai CHECK (SoDienThoai NOT LIKE '%[^0-9]%' AND LEN(SoDienThoai) BETWEEN 9 AND 11)
);

CREATE TABLE dbo.PHUONGTIEN
(
    MaPT            VARCHAR(20)    NOT NULL,
    BienSo          VARCHAR(20)    NOT NULL,
    LoaiXe          NVARCHAR(20)   NOT NULL,
    MaKH            VARCHAR(20)    NULL,
    NgayTaoUtc      DATETIME2(0)   NOT NULL CONSTRAINT DF_PHUONGTIEN_NgayTaoUtc DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_PHUONGTIEN PRIMARY KEY (MaPT),
    CONSTRAINT UQ_PHUONGTIEN_BienSo UNIQUE (BienSo),
    CONSTRAINT FK_PHUONGTIEN_KHACHHANG FOREIGN KEY (MaKH) REFERENCES dbo.KHACHHANG(MaKH),
    CONSTRAINT CK_PHUONGTIEN_LoaiXe CHECK (LoaiXe IN (N'Ô tô', N'Xe máy'))
);

CREATE TABLE dbo.LOAIVE
(
    MaLoaiVe        VARCHAR(20)    NOT NULL,
    TenLoaiVe      NVARCHAR(50)   NOT NULL,
    KyHieu          VARCHAR(10)    NOT NULL,
    CONSTRAINT PK_LOAIVE PRIMARY KEY (MaLoaiVe),
    CONSTRAINT UQ_LOAIVE_TenLoaiVe UNIQUE (TenLoaiVe),
    CONSTRAINT UQ_LOAIVE_KyHieu UNIQUE (KyHieu),
    CONSTRAINT CK_LOAIVE_KyHieu CHECK (KyHieu IN ('LUOT', 'THANG'))
);

CREATE TABLE dbo.VE
(
    MaVe            VARCHAR(20)    NOT NULL,
    MaThe           VARCHAR(30)    NOT NULL,
    MaLoaiVe        VARCHAR(20)    NOT NULL,
    NgayCap         DATE           NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_VE_TrangThai DEFAULT ('HOAT_DONG'),
    CONSTRAINT PK_VE PRIMARY KEY (MaVe),
    CONSTRAINT UQ_VE_MaThe UNIQUE (MaThe),
    CONSTRAINT FK_VE_LOAIVE FOREIGN KEY (MaLoaiVe) REFERENCES dbo.LOAIVE(MaLoaiVe),
    CONSTRAINT CK_VE_TrangThai CHECK (TrangThai IN ('HOAT_DONG', 'KHOA', 'HONG'))
);

CREATE TABLE dbo.BANGGIA
(
    MaBangGia       VARCHAR(20)    NOT NULL,
    LoaiXe          NVARCHAR(20)   NOT NULL,
    MaLoaiVe        VARCHAR(20)    NOT NULL,
    DonGia          DECIMAL(18,2)  NOT NULL,
    DonGiaSau19Gio  DECIMAL(18,2)  NULL,
    DonGiaQuaDem    DECIMAL(18,2)  NULL,
    NgayApDung      DATE           NOT NULL,
    CONSTRAINT PK_BANGGIA PRIMARY KEY (MaBangGia),
    CONSTRAINT UQ_BANGGIA_LoaiXeLoaiVeNgay UNIQUE (LoaiXe, MaLoaiVe, NgayApDung),
    CONSTRAINT FK_BANGGIA_LOAIVE FOREIGN KEY (MaLoaiVe) REFERENCES dbo.LOAIVE(MaLoaiVe),
    CONSTRAINT CK_BANGGIA_LoaiXe CHECK (LoaiXe IN (N'Ô tô', N'Xe máy')),
    CONSTRAINT CK_BANGGIA_DonGia CHECK (DonGia > 0),
    CONSTRAINT CK_BANGGIA_DonGiaSau19Gio CHECK (DonGiaSau19Gio IS NULL OR DonGiaSau19Gio > 0),
    CONSTRAINT CK_BANGGIA_DonGiaQuaDem CHECK (DonGiaQuaDem IS NULL OR DonGiaQuaDem > 0)
);

CREATE TABLE dbo.KHUVUC
(
    MaKhuVuc        VARCHAR(20)    NOT NULL,
    TenKhuVuc      NVARCHAR(100)  NOT NULL,
    LoaiXe          NVARCHAR(20)   NOT NULL,
    SucChua         INT            NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_KHUVUC_TrangThai DEFAULT ('HOAT_DONG'),
    CONSTRAINT PK_KHUVUC PRIMARY KEY (MaKhuVuc),
    CONSTRAINT UQ_KHUVUC_TenKhuVuc UNIQUE (TenKhuVuc),
    CONSTRAINT CK_KHUVUC_LoaiXe CHECK (LoaiXe IN (N'Ô tô', N'Xe máy')),
    CONSTRAINT CK_KHUVUC_SucChua CHECK (SucChua > 0),
    CONSTRAINT CK_KHUVUC_TrangThai CHECK (TrangThai IN ('HOAT_DONG', 'BAO_TRI', 'TAM_DONG'))
);

CREATE TABLE dbo.DANGKYVETHANG
(
    MaDangKy        VARCHAR(20)    NOT NULL,
    MaKH            VARCHAR(20)    NOT NULL,
    MaPT            VARCHAR(20)    NOT NULL,
    MaVe            VARCHAR(20)    NOT NULL,
    NgayBatDau      DATE           NOT NULL,
    NgayKetThuc     DATE           NOT NULL,
    SoThang         TINYINT        NOT NULL,
    DonGiaThang     DECIMAL(18,2)  NOT NULL,
    TongTien        DECIMAL(18,2)  NOT NULL,
    ThanhToan       VARCHAR(20)    NOT NULL CONSTRAINT DF_DANGKYVETHANG_ThanhToan DEFAULT ('CHUA_THANH_TOAN'),
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_DANGKYVETHANG_TrangThai DEFAULT ('CHO_THANH_TOAN'),
    NgayTaoUtc      DATETIME2(0)   NOT NULL CONSTRAINT DF_DANGKYVETHANG_NgayTaoUtc DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_DANGKYVETHANG PRIMARY KEY (MaDangKy),
    CONSTRAINT FK_DANGKYVETHANG_KHACHHANG FOREIGN KEY (MaKH) REFERENCES dbo.KHACHHANG(MaKH),
    CONSTRAINT FK_DANGKYVETHANG_PHUONGTIEN FOREIGN KEY (MaPT) REFERENCES dbo.PHUONGTIEN(MaPT),
    CONSTRAINT FK_DANGKYVETHANG_VE FOREIGN KEY (MaVe) REFERENCES dbo.VE(MaVe),
    CONSTRAINT CK_DANGKYVETHANG_Ngay CHECK (NgayKetThuc > NgayBatDau),
    CONSTRAINT CK_DANGKYVETHANG_SoThang CHECK (SoThang BETWEEN 1 AND 24),
    CONSTRAINT CK_DANGKYVETHANG_Tien CHECK (DonGiaThang > 0 AND TongTien = DonGiaThang * SoThang),
    CONSTRAINT CK_DANGKYVETHANG_ThanhToan CHECK (ThanhToan IN ('CHUA_THANH_TOAN', 'DA_THANH_TOAN', 'HOAN_TIEN')),
    CONSTRAINT CK_DANGKYVETHANG_TrangThai CHECK (TrangThai IN ('CHO_THANH_TOAN', 'HIEU_LUC', 'HET_HAN', 'HUY'))
);

CREATE TABLE dbo.LUOTGUIXE
(
    MaLuotGui       VARCHAR(20)    NOT NULL,
    MaPT            VARCHAR(20)    NOT NULL,
    MaVe            VARCHAR(20)    NOT NULL,
    MaKhuVuc        VARCHAR(20)    NOT NULL,
    ThoiGianVaoUtc  DATETIME2(0)   NOT NULL CONSTRAINT DF_LUOTGUIXE_ThoiGianVaoUtc DEFAULT (SYSUTCDATETIME()),
    ThoiGianRaUtc   DATETIME2(0)   NULL,
    TienGui         DECIMAL(18,2)  NOT NULL CONSTRAINT DF_LUOTGUIXE_TienGui DEFAULT (0),
    MaNVVao         VARCHAR(20)    NOT NULL,
    MaNVRa          VARCHAR(20)    NULL,
    LoaiVe          VARCHAR(10)    NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL CONSTRAINT DF_LUOTGUIXE_TrangThai DEFAULT ('DANG_GUI'),
    CONSTRAINT PK_LUOTGUIXE PRIMARY KEY (MaLuotGui),
    CONSTRAINT FK_LUOTGUIXE_PHUONGTIEN FOREIGN KEY (MaPT) REFERENCES dbo.PHUONGTIEN(MaPT),
    CONSTRAINT FK_LUOTGUIXE_VE FOREIGN KEY (MaVe) REFERENCES dbo.VE(MaVe),
    CONSTRAINT FK_LUOTGUIXE_KHUVUC FOREIGN KEY (MaKhuVuc) REFERENCES dbo.KHUVUC(MaKhuVuc),
    CONSTRAINT FK_LUOTGUIXE_NHANVIEN_VAO FOREIGN KEY (MaNVVao) REFERENCES dbo.NHANVIEN(MaNV),
    CONSTRAINT FK_LUOTGUIXE_NHANVIEN_RA FOREIGN KEY (MaNVRa) REFERENCES dbo.NHANVIEN(MaNV),
    CONSTRAINT CK_LUOTGUIXE_LoaiVe CHECK (LoaiVe IN ('LUOT', 'THANG')),
    CONSTRAINT CK_LUOTGUIXE_TrangThai CHECK (TrangThai IN ('DANG_GUI', 'DA_RA', 'HUY')),
    CONSTRAINT CK_LUOTGUIXE_ThoiGian CHECK (ThoiGianRaUtc IS NULL OR ThoiGianRaUtc >= ThoiGianVaoUtc),
    CONSTRAINT CK_LUOTGUIXE_TienGui CHECK (TienGui >= 0),
    CONSTRAINT CK_LUOTGUIXE_DongMo CHECK
    (
        (TrangThai = 'DANG_GUI' AND ThoiGianRaUtc IS NULL AND MaNVRa IS NULL)
        OR
        (TrangThai IN ('DA_RA', 'HUY') AND ThoiGianRaUtc IS NOT NULL)
    )
);

CREATE TABLE dbo.THANHTOAN
(
    MaThanhToan     VARCHAR(20)    NOT NULL,
    LoaiThanhToan  VARCHAR(20)    NOT NULL,
    MaLuotGui       VARCHAR(20)    NULL,
    MaDangKy        VARCHAR(20)    NULL,
    SoTien          DECIMAL(18,2)  NOT NULL,
    ThoiGianUtc     DATETIME2(0)   NOT NULL CONSTRAINT DF_THANHTOAN_ThoiGianUtc DEFAULT (SYSUTCDATETIME()),
    PhuongThuc      VARCHAR(20)    NOT NULL,
    TrangThai       VARCHAR(20)    NOT NULL,
    MaNV            VARCHAR(20)    NOT NULL,
    MaThamChieu     VARCHAR(100)   NULL,
    GhiChu          NVARCHAR(255)  NULL,
    CONSTRAINT PK_THANHTOAN PRIMARY KEY (MaThanhToan),
    CONSTRAINT FK_THANHTOAN_LUOTGUIXE FOREIGN KEY (MaLuotGui) REFERENCES dbo.LUOTGUIXE(MaLuotGui),
    CONSTRAINT FK_THANHTOAN_DANGKYVETHANG FOREIGN KEY (MaDangKy) REFERENCES dbo.DANGKYVETHANG(MaDangKy),
    CONSTRAINT FK_THANHTOAN_NHANVIEN FOREIGN KEY (MaNV) REFERENCES dbo.NHANVIEN(MaNV),
    CONSTRAINT CK_THANHTOAN_Loai CHECK (LoaiThanhToan IN ('VE_LUOT', 'VE_THANG')),
    CONSTRAINT CK_THANHTOAN_SoTien CHECK (SoTien > 0),
    CONSTRAINT CK_THANHTOAN_PhuongThuc CHECK (PhuongThuc IN ('TIEN_MAT', 'CHUYEN_KHOAN', 'THE')),
    CONSTRAINT CK_THANHTOAN_TrangThai CHECK (TrangThai IN ('CHO_XU_LY', 'THANH_CONG', 'THAT_BAI', 'HOAN_TIEN')),
    CONSTRAINT CK_THANHTOAN_Nguon CHECK
    (
        (LoaiThanhToan = 'VE_LUOT' AND MaLuotGui IS NOT NULL AND MaDangKy IS NULL)
        OR
        (LoaiThanhToan = 'VE_THANG' AND MaLuotGui IS NULL AND MaDangKy IS NOT NULL)
    )
);

/* Mot xe va mot the chi co toi da mot luot gui dang mo. */
CREATE UNIQUE INDEX UX_LUOTGUIXE_MaPT_DangGui
    ON dbo.LUOTGUIXE(MaPT)
    WHERE TrangThai = 'DANG_GUI';

CREATE UNIQUE INDEX UX_LUOTGUIXE_MaVe_DangGui
    ON dbo.LUOTGUIXE(MaVe)
    WHERE TrangThai = 'DANG_GUI';

CREATE INDEX IX_LUOTGUIXE_ThoiGianVaoUtc ON dbo.LUOTGUIXE(ThoiGianVaoUtc DESC);
CREATE INDEX IX_LUOTGUIXE_TrangThai_KhuVuc ON dbo.LUOTGUIXE(TrangThai, MaKhuVuc);
CREATE INDEX IX_DANGKYVETHANG_PhuongTien_ThoiHan ON dbo.DANGKYVETHANG(MaPT, NgayBatDau, NgayKetThuc);
CREATE INDEX IX_DANGKYVETHANG_The_ThoiHan ON dbo.DANGKYVETHANG(MaVe, NgayBatDau, NgayKetThuc);
CREATE INDEX IX_THANHTOAN_ThoiGianUtc_TrangThai ON dbo.THANHTOAN(ThoiGianUtc, TrangThai);
CREATE INDEX IX_PHANCONGCA_NgayLam ON dbo.PHANCONGCA(NgayLam, MaCa);
GO

